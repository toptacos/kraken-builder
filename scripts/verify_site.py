#!/usr/bin/env python3
"""Verify the marketing site: links resolve, taxonomy terms are registered,
and taxonomy pages are discoverable in the sitemap.

Runs on Linux, macOS, and Windows: file and JSON checks, no network, no
shell. Both a human (`python3 scripts/verify_site.py`) and the test suite
(`tests/test_site.py`, which imports this module) use the same functions, so
the two can never disagree about what "verified" means.
"""

from __future__ import annotations

import json
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SITE = ROOT / "website"
REGISTRY = SITE / "data" / "taxonomy.json"

#: href/src values that are not site-relative files: anchors, mail, tel,
#: http(s), and the dynamic routes the deployed site serves.
NON_FILE = re.compile(r"^(#|mailto:|tel:|https?:|data:|javascript:)")

#: Paths generated by the media build and not committed to the repo. A link
#: into them cannot be verified on a fresh clone, so it is out of scope for
#: this check (and generating them is a separate, network-reaching step).
GENERATED = ("media/", "courses/videos/")


def problems() -> list[str]:
    found: list[str] = []
    if not SITE.is_dir():
        return [f"no website directory at {SITE}"]

    registry = load_registry()
    terms = {
        t["slug"]
        for tax in registry.get("taxonomies", {}).values()
        for t in tax.get("terms", [])
    }
    for tax in registry.get("taxonomies", {}).values():
        for term in tax.get("terms", []):
            if not {"slug", "name", "description"} <= set(term):
                found.append(f"taxonomy term missing keys: {term}")

    pages = sorted(SITE.glob("*.html"))
    if not pages:
        found.append("no html pages found in website/")
    sitemap = (SITE / "sitemap.xml").read_text(encoding="utf-8")
    taxonomy_pages: list[str] = []

    for page in pages:
        text = page.read_text(encoding="utf-8")
        # local href/src must resolve to a file in website/
        for attr in re.findall(r'(?:href|src)="([^"]+)"', text):
            if NON_FILE.match(attr):
                continue
            target = attr.split("#", 1)[0]
            if not target or target in (".", "./"):
                # "./" is the site root; index.html is what serves there.
                target = "index.html"
            if target.startswith(GENERATED):
                continue
            if not (SITE / target).is_file():
                found.append(f"{page.name}: broken link {attr!r}")
        # taxonomy tagging must use a registered term
        meta = re.search(r'<meta name="taxonomy" content="([^"]+)"', text)
        body = re.search(r'data-taxonomy="([^"]+)"', text)
        declared = {
            v
            for v in (meta.group(1) if meta else None, body.group(1) if body else None)
            if v
        }
        for tag in declared:
            tax, _, term = tag.partition(":")
            if not term:
                found.append(f"{page.name}: taxonomy tag {tag!r} is not name:term")
                continue
            if tax not in registry.get("taxonomies", {}):
                found.append(f"{page.name}: unknown taxonomy {tax!r}")
            elif term not in terms:
                found.append(f"{page.name}: unregistered term {term!r}")
        if meta and not body:
            found.append(f"{page.name}: taxonomy in <head> but not on <body>")
        if body and not meta:
            found.append(f"{page.name}: taxonomy on <body> but not in <head>")
        if body:
            taxonomy_pages.append(page.name)
            loc = f"https://kraken.topta.co/{page.name}"
            if loc not in sitemap:
                found.append(f"{page.name}: tagged page missing from sitemap.xml")

    # sitemap entries must exist as files or a known deployed route
    routes = {"/blog", "/cli", "/catalog", "/changelog"}
    for loc in re.findall(r"<loc>https://kraken\.topta\.co(/[^<]*)</loc>", sitemap):
        path = loc.lstrip("/")
        if loc in routes or path == "":
            continue
        if not (SITE / path).is_file():
            found.append(f"sitemap.xml: missing file for {loc}")

    # the two content pages that started this taxonomy must exist and be tagged
    for required in ("compare.html", "blog-why-kraken.html"):
        if required not in taxonomy_pages:
            found.append(f"{required} must be tagged with the kraken project term")
    return found


def load_registry() -> dict:
    if not REGISTRY.is_file():
        return {}
    return json.loads(REGISTRY.read_text(encoding="utf-8"))


def main() -> int:
    found = problems()
    pages = sorted(SITE.glob("*.html")) if SITE.is_dir() else []
    print(f"checked {len(pages)} page(s) against website/data/taxonomy.json")
    for p in found:
        print("FAIL", p)
    if found:
        print(f"{len(found)} problem(s)")
        return 1
    print("site OK")
    return 0


if __name__ == "__main__":
    sys.exit(main())
